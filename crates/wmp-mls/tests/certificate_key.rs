/// One imported-key case: the chain (leaf first), the PKCS#8 private
/// key, the public key the leaf must sign with, and the suite that
/// matches the key's algorithm (RFC 9420 §5.1: the leaf's scheme
/// SHOULD be the ciphersuite's).
struct Case {
    name: &'static str,
    chain: Option<Vec<Vec<u8>>>,
    key: &'static [u8],
    public: &'static [u8],
    suite: i64,
}

/// RFC 9420 §5.3.1: the group the provider mints carries the signer's
/// key in its creator leaf — and that key is the certificate's own
/// public key, the openssl vector, not a fresh pair. The P-256 case is
/// the regression: before the import, a P-256 chain was signed by a
/// fresh Ed25519 key and the leaf carried the wrong public.
#[test]
fn the_leaf_signs_with_the_certificates_own_key() {
    let cases = [
        Case {
            name: "P-256",
            chain: Some(vec![P256_CERT_DER.to_vec()]),
            key: P256_KEY_PKCS8,
            public: P256_PUBLIC_SEC1,
            suite: wmp_core::mls::CIPHER_SUITE_P256_AES128_GCM,
        },
        Case {
            name: "Ed25519",
            chain: None,
            key: ED_KEY_PKCS8,
            public: ED_PUBLIC,
            suite: wmp_core::mls::CIPHER_SUITE_X25519_AES128_GCM,
        },
    ];
    for case in cases {
        let provider = OpenMlsProvider::for_identity_with_certificate_and_key(
            "wallet-a",
            case.chain.clone(),
            Some(case.key.to_vec()),
        )
        .expect("the provider mints from the certificate's key");
        let (group_id, _) = provider
            .create_group(case.suite, &[])
            .expect("the group mints");
        let info = provider
            .export_group_info(&group_id)
            .expect("the GroupInfo exports");

        // The oracle walk: openmls's own decoder reads the GroupInfo and
        // its ratchet tree back off the wire — the provider's strings
        // are all the provider exposes.
        use openmls::prelude::tls_codec::Deserialize as _;
        let message =
            openmls::framing::MlsMessageIn::tls_deserialize_exact(decode(&info).as_slice())
                .expect("the GroupInfo parses");
        let group_info = match message.extract() {
            openmls::framing::MlsMessageBodyIn::GroupInfo(group_info) => group_info,
            _ => panic!("the export carries a GroupInfo"),
        };
        let tree = group_info
            .extensions()
            .ratchet_tree()
            .expect("the tree rides the GroupInfo (RFC 9420 §7.2)");
        let (_, leaf) = tree
            .ratchet_tree()
            .full_leaves()
            .next()
            .expect("the creator's leaf rides the tree");
        assert_eq!(
            leaf.signature_key().as_slice(),
            case.public,
            "{}: the leaf signs with the certificate's own key",
            case.name,
        );
        // The credential the leaf carries: the X.509 chain (its content
        // ends with the leaf certificate's DER) when the chain arrives,
        // the basic identity otherwise (wmp-mls §2.2).
        let credential = leaf.credential();
        match case.chain.as_deref().map(<[Vec<u8>]>::first) {
            Some(Some(cert)) => {
                assert_eq!(
                    credential.credential_type(),
                    openmls::credentials::CredentialType::X509,
                    "{}: the credential is the certificate",
                    case.name,
                );
                assert!(
                    credential.serialized_content().ends_with(cert),
                    "{}: the credential carries the leaf certificate",
                    case.name,
                );
            }
            _ => {
                assert_eq!(
                    credential.credential_type(),
                    openmls::credentials::CredentialType::Basic,
                    "{}: the credential is the basic identity",
                    case.name,
                );
                assert_eq!(
                    credential.serialized_content(),
                    b"wallet-a",
                    "{}: the basic credential carries the identity",
                    case.name,
                );
            }
        }
    }
}

/// The certificate-keyed member's full lifecycle: the P-256 signer's
/// group — created, joined by a second member, encrypted into — must
/// work end to end, because every step's signatures (the GroupInfo's,
/// the commit's, the message's authentication) are verified by MLS
/// itself against the leaf's key (RFC 9420 §5.4, §7): a member whose
/// signer did not match its credential could not add, join or decrypt.
#[test]
fn a_certificate_signed_member_runs_the_full_group_lifecycle() {
    let a = OpenMlsProvider::for_identity_with_certificate_and_key(
        "wallet-a",
        Some(vec![P256_CERT_DER.to_vec()]),
        Some(P256_KEY_PKCS8.to_vec()),
    )
    .expect("A mints from the certificate's key");
    // B holds a P-256 key of its own (issue #127: the package carries the
    // CONFIGURED signer — a 0x0002 member signs with P-256, so the basic
    // Ed25519 shape no longer mints a fresh key beside the identity).
    let b = OpenMlsProvider::for_identity_with_certificate_and_key(
        "wallet-b",
        None,
        Some(P256_KEY_B_PKCS8.to_vec()),
    )
    .expect("B mints from its own P-256 key");
    let (group_id, _) = a
        .create_group(wmp_core::mls::CIPHER_SUITE_P256_AES128_GCM, &[])
        .expect("A creates on the P-256 suite");
    let package = b
        .generate_key_package(wmp_core::mls::CIPHER_SUITE_P256_AES128_GCM)
        .expect("B's package");
    let (_commit, welcome) = a
        .add_member(&group_id, &package.key_package)
        .expect("A adds B");
    let (b_group, _epoch) = b.process_welcome(&welcome).expect("B joins");

    let plaintext = b"signed by the certificate's own key".to_vec();
    let (ciphertext, _epoch) = a
        .encrypt(&group_id, &plaintext)
        .expect("A encrypts with the P-256 leaf");
    let (decrypted, _) = b
        .decrypt(&b_group, &ciphertext)
        .expect("B decrypts the certificate-signed member's message");
    assert_eq!(decrypted, plaintext, "the round trip answers the plaintext");
}

/// A key of an algorithm the suites do not carry (P-384) refuses the MLS
/// error — fail closed, never a fresh-key fallback that would sign beside
/// the certificate.
#[test]
fn an_unsupported_key_algorithm_refuses() {
    let refused = OpenMlsProvider::for_identity_with_certificate_and_key(
        "wallet-a",
        Some(vec![P256_CERT_DER.to_vec()]),
        Some(P384_KEY_PKCS8.to_vec()),
    )
    .map(|provider| provider.identity().to_owned())
    .expect_err("a P-384 key refuses");
    assert_eq!(refused.to_rpc().code, wmp_core::error::ERR_MLS_ERROR);
}

// ─── The test-side codec ───────────────────────────────────────────────────

/// base64url decode — the test-side twin of the provider's own codec
/// (the assertions parse what the provider serialized).
fn decode(encoded: &str) -> Vec<u8> {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
    let mut out = Vec::with_capacity(encoded.len() * 3 / 4);
    let mut buffer: u32 = 0;
    let mut bits = 0u32;
    for byte in encoded.bytes() {
        if byte == b'=' {
            break;
        }
        let value = ALPHABET.iter().position(|&a| a == byte).expect("base64url") as u32;
        buffer = (buffer << 6) | value;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((buffer >> bits) as u8);
        }
    }
    out
}

/// The certificate-bound member's PUBLISHED package carries the
/// configured identity end to end (issue #127, RFC 9420 §5.3.1): the
/// leaf's signature key is the certificate's own key and the credential
/// is the X.509 chain — the same credential the provider's own group
/// operations use, so the group peers see the configured identity in
/// the leaf, never a self-asserted basic one beside a key the member
/// cannot sign with.
#[test]
fn a_certificate_bound_members_package_carries_the_chain_and_the_signers_key() {
    let provider = OpenMlsProvider::for_identity_with_certificate_and_key(
        "wallet-a",
        Some(vec![P256_CERT_DER.to_vec()]),
        Some(P256_KEY_PKCS8.to_vec()),
    )
    .expect("the provider mints from the certificate's key");
    let package = provider
        .generate_key_package(wmp_core::mls::CIPHER_SUITE_P256_AES128_GCM)
        .expect("the certificate's signer serves the P-256 suite");

    // The oracle walk: openmls's own wire decoder reads the package
    // back — the provider hands out only strings.
    use openmls::prelude::tls_codec::Deserialize as _;
    use openmls_traits::OpenMlsProvider as _;
    let crypto = openmls_rust_crypto::OpenMlsRustCrypto::default();
    let package_in = openmls::key_packages::KeyPackageIn::tls_deserialize_exact(
        decode(&package.key_package).as_slice(),
    )
    .expect("the package parses off the wire");
    let parsed = package_in
        .validate(
            crypto.crypto(),
            openmls::versions::ProtocolVersion::default(),
        )
        .expect("the package validates");
    let leaf = parsed.leaf_node();
    assert_eq!(
        leaf.signature_key().as_slice(),
        P256_PUBLIC_SEC1,
        "the package's leaf signs with the certificate's own key",
    );
    let credential = leaf.credential();
    assert_eq!(
        credential.credential_type(),
        openmls::credentials::CredentialType::X509,
        "the package's credential is the certificate",
    );
    assert!(
        credential.serialized_content().ends_with(P256_CERT_DER),
        "the package's credential carries the leaf certificate",
    );
}
