//! The certificate key import (issue #114): RFC 9420 §5.3.1 — the leaf
//! node's signature key is the credential's key, so a member whose chain's
//! leaf is P-256 must sign with that P-256 key, never with a fresh Ed25519
//! pair minted beside the certificate (the mismatch: peers that resolve
//! the member BY CERTIFICATE refuse — "the leaf node signature is not
//! valid").
//!
//! The oracle: the ratchet tree the creator's GroupInfo export carries
//! (RFC 9420 §7.2 — the tree rides the GroupInfo's extension; the
//! provider's create pins `use_ratchet_tree_extension`), parsed here by
//! openmls's own wire decoder — the provider hands out only strings.
//! The expected public keys are openssl-minted vectors, an
//! implementation independent of this crate: the leaf's signature key
//! must be exactly the certificate's key.
//!
//! The fixtures: real openssl certificates and keys — P-256 (a
//! subscriber certificate + its PKCS#8 private key + the SPKI's public
//! point), Ed25519 (RFC 8410 §7's PKCS#8 seed form), and P-384 (the
//! refusal case: a valid key of an unsupported algorithm).

use wmp_core::mls::MlsProvider;
use wmp_mls::OpenMlsProvider;

